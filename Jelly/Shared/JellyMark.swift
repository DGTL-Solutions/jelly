/// The app icon as a view: the violet-to-blue tile with the milky glass jellyfish on it. `size` is the width of the tile.
struct JellyMark: View {
    var size: CGFloat = 96

    var body: some View {
        RoundedRectangle(cornerRadius: size * 0.223, style: .continuous)
            .fill(LinearGradient(colors: [Color(red: 0.42, green: 0.25, blue: 0.98), Color(red: 0.08, green: 0.62, blue: 1.0)],
                                 startPoint: .topLeading, endPoint: .bottomTrailing))
            .frame(width: size, height: size)
            .overlay {
                JellyShape()
                    .fill(LinearGradient(colors: [.white.opacity(0.97), .white.opacity(0.60)],
                                         startPoint: UnitPoint(x: 0.3, y: 0), endPoint: UnitPoint(x: 0.7, y: 1)))
                    .overlay { JellyShape().stroke(.white.opacity(0.9), lineWidth: max(1, size * 0.006)) }
                    .shadow(color: Color(red: 0.10, green: 0.05, blue: 0.42).opacity(0.35), radius: size * 0.04, y: size * 0.03)
                    .frame(width: size * 0.70, height: size * 0.70 / JellyShape.aspect)
            }
            .shadow(color: Color(red: 0.4, green: 0.3, blue: 0.9).opacity(0.35), radius: size * 0.16, y: size * 0.05)
            .accessibilityHidden(true)
    }
}
